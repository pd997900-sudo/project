  /// Parse text or address to identify State and District
  static Map<String, String>? detectFromAddress(String? address) {
    if (address == null || address.trim().isEmpty) return null;
    final text = address.toLowerCase();

    // 1. Check known locality mapping
    for (var entry in localityMapping.entries) {
      if (text.contains(entry.key)) {
        return entry.value;
      }
    }

    // 2. Check all known districts across states
    for (var stateEntry in stateDistricts.entries) {
      final stateName = stateEntry.key;
      for (var district in stateEntry.value) {
        final distLower = district.toLowerCase().replaceAll(RegExp(r'\(.*\)'), '').trim();
        if (distLower.length > 3 && text.contains(distLower)) {
          return {'state': stateName, 'district': district};
        }
      }
    }

    // 3. Check states
    for (var state in states) {
      if (text.contains(state.toLowerCase())) {
        final firstDist = getDistricts(state).first;
        return {'state': state, 'district': firstDist};
      }
    }

    return null;
  }
