  static List<String> get states => stateDistricts.keys.toList()..sort();

  static List<String> getDistricts(String? state) {
    if (state == null || state.trim().isEmpty) {
      return stateDistricts['Tamil Nadu']!;
    }
    final cleanState = state.trim();
    for (var entry in stateDistricts.entries) {
      if (entry.key.toLowerCase() == cleanState.toLowerCase()) {
        return List<String>.from(entry.value)..sort();
      }
    }
    return ['General District'];
  }

